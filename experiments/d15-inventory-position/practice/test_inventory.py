"""Hand arithmetic, causality, and intentionally corrupted accounting records."""
import copy
import csv
import json
import shutil
import tempfile
from pathlib import Path
import hashlib
import subprocess
import sys
import unittest
from decimal import Decimal
from run import ROOT, load_case, simulate, audit, decide_order, number


class InventoryTests(unittest.TestCase):
    def setUp(self):
        self.c, self.rows = load_case('hewei')
        self.ledger, self.events = simulate(self.c, self.rows)

    def test_hewei_hand_calculated_all_days(self):
        # Independent pencil-and-paper values, not generated by the simulator.
        expected = {
            'arrivals': [0,8,0,7,9,4,4],
            'served': [7,9,4,4,5,6,3],
            'lost_sales': [0,0,4,0,0,0,0],
            'closing_on_hand': [5,4,0,3,7,5,6],
            'on_order_before_order': [8,7,16,13,8,9,11],
            'ip_before_order': [13,11,16,16,15,14,17],
            'order_quantity': [7,9,4,4,5,6,3],
            'on_order_after_order': [15,16,20,17,13,15,14],
            'ip_after_order': [20]*7}
        for key, values in expected.items():
            self.assertEqual([r[key] for r in self.ledger], values, key)

    def test_apparel_hand_calculation(self):
        c, rows = load_case('apparel')
        ledger, _ = simulate(c, rows)
        self.assertEqual([r['order_quantity'] for r in ledger], [7,5,4,7,3,6,2])
        self.assertEqual([r['closing_on_hand'] for r in ledger], [5,0,3,1,2,3,4])
        self.assertEqual([r['lost_sales'] for r in ledger], [0,3,0,0,0,0,0])
        self.assertEqual(ledger[-1]['on_order_after_order'], 8)

    def test_total_material_conservation(self):
        for case in ('hewei', 'apparel'):
            c, rows = load_case(case)
            ledger, _ = simulate(c, rows)
            self.assertEqual(c['initial_on_hand']+sum(r['arrivals'] for r in ledger)-sum(r['served'] for r in ledger), ledger[-1]['closing_on_hand'])
            self.assertEqual(sum(o['quantity'] for o in c['initial_orders'])+sum(r['order_quantity']-r['arrivals'] for r in ledger), ledger[-1]['on_order_after_order'])
            self.assertEqual(sum(r['demand'] for r in ledger), sum(r['served']+r['lost_sales'] for r in ledger))

    def test_receipt_transfers_pipeline_without_changing_position(self):
        for r in self.ledger:
            self.assertEqual(r['opening_on_hand']+r['opening_on_order'], r['available_before_demand']+r['on_order_before_order'])
            self.assertEqual(r['ip_before_order'], r['opening_on_hand']+r['opening_on_order']-r['served'])

    def test_future_demand_does_not_change_issued_orders(self):
        for cutoff in range(1, 7):
            altered = copy.deepcopy(self.rows)
            for r in altered[cutoff:]:
                r['demand'] = '999'
            changed, _ = simulate(self.c, altered)
            self.assertEqual(changed[:cutoff], self.ledger[:cutoff])

    def test_prefix_alone_has_same_decisions(self):
        for cutoff in range(1, 8):
            c = dict(self.c, days=cutoff)
            prefix, _ = simulate(c, self.rows[:cutoff])
            self.assertEqual(prefix, self.ledger[:cutoff])

    def test_day_one_order_arrives_day_four_not_day_three(self):
        o = next(e for e in self.events if e['event'] == 'placed')
        self.assertEqual((o['placed_day'],o['arrival_day']), (1,4))
        corrupted = copy.deepcopy(self.events)
        for e in corrupted:
            if e['order_id'] == o['order_id']:
                e['arrival_day'] -= 1
                if e['event'] == 'arrival': e['event_day'] -= 1
        with self.assertRaises(ValueError): audit(self.c, self.rows, self.ledger, corrupted)

    def test_early_actual_arrival_rejected_even_with_correct_due_date(self):
        corrupted = copy.deepcopy(self.events)
        next(e for e in corrupted if e['event'] == 'arrival')['event_day'] -= 1
        with self.assertRaises(ValueError): audit(self.c, self.rows, self.ledger, corrupted)

    def test_lost_sales_not_subtracted_twice(self):
        bad = copy.deepcopy(self.ledger)
        bad[2]['ip_before_order'] -= 4
        bad[2]['order_quantity'] += 4
        with self.assertRaises(ValueError): audit(self.c, self.rows, bad, self.events)
        self.assertEqual(self.ledger[2]['order_quantity'],4)

    def test_forgetting_pipeline_debit_on_receipt_rejected(self):
        bad = copy.deepcopy(self.ledger)
        bad[1]['on_order_before_order'] += 8
        with self.assertRaises(ValueError): audit(self.c, self.rows, bad, self.events)

    def test_on_hand_only_reordering_counterexample(self):
        row = self.ledger[0]
        wrong = 20-row['closing_on_hand']
        self.assertEqual(wrong,15)
        self.assertEqual(row['order_quantity'],7)
        bad = copy.deepcopy(self.ledger)
        bad[0]['order_quantity'] = wrong
        with self.assertRaises(ValueError): audit(self.c, self.rows, bad, self.events)

    def test_negative_nan_infinite_demand_rejected(self):
        for value in ('NaN','Infinity','-Infinity','-1','nonsense','1000001','0.0001'):
            with self.subTest(value=value):
                rows = copy.deepcopy(self.rows); rows[0]['demand']=value
                with self.assertRaises(ValueError): simulate(self.c,rows)

    def test_invalid_dates_duplicate_day_and_missing_rows(self):
        for value in ('2026-02-30','2026-01-02','2026-1-1','20260101'):
            rows=copy.deepcopy(self.rows);rows[0]['date']=value
            with self.assertRaises(ValueError): simulate(self.c,rows)
        rows=copy.deepcopy(self.rows);rows[1]['day']='1'
        with self.assertRaises(ValueError): simulate(self.c,rows)
        with self.assertRaises(ValueError): simulate(self.c,self.rows[:-1])

    def test_units_cases_and_entities_cannot_cross(self):
        for key,value in [('unit','pieces'),('series','hewei/B/SKU01'),('case','apparel')]:
            rows=copy.deepcopy(self.rows);rows[3][key]=value
            with self.assertRaises(ValueError): simulate(self.c,rows)
            c=copy.deepcopy(self.c);c['initial_orders'][0][key]=value
            with self.assertRaises(ValueError): simulate(c,self.rows)

    def test_duplicate_initial_order_and_event_rejected(self):
        c=copy.deepcopy(self.c);c['initial_orders']*=2
        with self.assertRaises(ValueError): simulate(c,self.rows)
        with self.assertRaises(ValueError): audit(self.c,self.rows,self.ledger,self.events+[self.events[0]])

    def test_partial_receipt_and_cancellation_rejected(self):
        events=copy.deepcopy(self.events)
        next(e for e in events if e['event']=='arrival')['quantity']-=1
        with self.assertRaises(ValueError): audit(self.c,self.rows,self.ledger,events)
        events=copy.deepcopy(self.events);events[0]['event']='cancelled'
        with self.assertRaises(ValueError): audit(self.c,self.rows,self.ledger,events)
        c=copy.deepcopy(self.c);c['initial_orders'][0]['remaining_quantity']=4
        with self.assertRaises(ValueError): simulate(c,self.rows)

    def test_every_event_type_rejects_unknown_or_missing_fields(self):
        for event_type in ('initial_open', 'placed', 'arrival'):
            for mutation in ('extra', 'missing'):
                with self.subTest(event_type=event_type, mutation=mutation):
                    events = copy.deepcopy(self.events)
                    event = next(e for e in events if e['event'] == event_type)
                    if mutation == 'extra':
                        event['cancelled_quantity'] = 3
                    else:
                        del event['quantity']
                    with self.assertRaisesRegex(ValueError, 'unexpected event fields'):
                        audit(self.c, self.rows, self.ledger, events)

    def test_ledger_rejects_unknown_or_missing_fields(self):
        for mutation in ('extra', 'missing'):
            ledger = copy.deepcopy(self.ledger)
            if mutation == 'extra':
                ledger[0]['backorders'] = 3
            else:
                del ledger[0]['lost_sales']
            with self.assertRaisesRegex(ValueError, 'unexpected ledger fields'):
                audit(self.c, self.rows, ledger, self.events)

    def test_missing_arrival_and_duplicate_arrival_rejected(self):
        arrival=next(e for e in self.events if e['event']=='arrival')
        with self.assertRaises(ValueError): audit(self.c,self.rows,self.ledger,[e for e in self.events if e is not arrival])
        with self.assertRaises(ValueError): audit(self.c,self.rows,self.ledger,self.events+[arrival])

    def test_invalid_configuration(self):
        for key,value in [('lead_time',-1),('lead_time',True),('days',0),('initial_on_hand','NaN'),('order_up_to',-1),('shortage_mode','backorder'),('start_date','2026-02-30')]:
            c=copy.deepcopy(self.c);c[key]=value
            with self.assertRaises(ValueError): simulate(c,self.rows)

    def test_zero_lead_time_means_next_day(self):
        c=copy.deepcopy(self.c);c.update(lead_time=0,initial_orders=[])
        ledger,events=simulate(c,self.rows)
        for e in events:
            self.assertEqual(e['arrival_day'], e['placed_day']+1)
        self.assertEqual(ledger[0]['arrivals'],0)
        self.assertEqual(ledger[1]['arrivals'],15)

    def test_excess_position_does_not_cancel_stock(self):
        self.assertEqual(decide_order(Decimal(30),Decimal(5),Decimal(20)),0)

    def test_fractional_kg_but_not_fractional_pieces(self):
        self.assertEqual(number('1.125','kg'),Decimal('1.125'))
        with self.assertRaises(ValueError): number('1.5','pieces')

    def test_main_empty_events_still_writes_headers_and_summary(self):
        # Exercise the actual CLI, not only simulate/write_csv. The altered fixture
        # and its explicit manifest live in isolation; shipped inputs stay frozen.
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            shutil.copy(ROOT/'run.py', root/'run.py')
            shutil.copytree(ROOT/'data', root/'data')
            configs = json.loads((ROOT/'parameters.json').read_text())
            for c in configs.values():
                c.update(initial_on_hand=0, initial_orders=[], order_up_to=0)
            (root/'parameters.json').write_text(json.dumps(configs))
            files = ['parameters.json', 'data/hewei-demand.csv', 'data/apparel-demand.csv']
            manifest = {'files': {name: hashlib.sha256((root/name).read_bytes()).hexdigest() for name in files}}
            (root/'source_manifest.json').write_text(json.dumps(manifest))
            subprocess.run([sys.executable, str(root/'run.py')], cwd=tmp,
                           check=True, stdout=subprocess.DEVNULL)
            summary = json.loads((root/'results/summary.json').read_text())
            for case, total in [('hewei',42), ('apparel',35)]:
                with (root/f'results/{case}-order-events.csv').open() as f:
                    reader = csv.DictReader(f)
                    self.assertEqual(reader.fieldnames, ['order_id','case','series','unit',
                        'placed_day','arrival_day','quantity','event','event_day'])
                    self.assertEqual(list(reader), [])
                with (root/f'results/{case}-ledger.csv').open() as f:
                    ledger = list(csv.DictReader(f))
                self.assertEqual(len(ledger), 7)
                self.assertTrue(all(Decimal(r['order_quantity']) == 0 for r in ledger))
                self.assertEqual(summary['cases'][case]['total_lost_sales'], total)
                self.assertEqual(summary['cases'][case]['total_served'], 0)
                self.assertEqual(summary['cases'][case]['closing_pending_orders'], [])
            hashes = json.loads((root/'results/output_hashes.json').read_text())
            for name, expected in hashes.items():
                self.assertEqual(hashlib.sha256((root/'results'/name).read_bytes()).hexdigest(), expected)

    def test_summary_pending_orders_are_explicit_and_conserve_pipeline(self):
        summary = json.loads((ROOT/'results/summary.json').read_text())['cases']
        self.assertEqual(summary['hewei']['closing_pending_orders'], [
            {'order_id':'new-hewei-005','arrival_day':8,'quantity':5},
            {'order_id':'new-hewei-006','arrival_day':9,'quantity':6},
            {'order_id':'new-hewei-007','arrival_day':10,'quantity':3}])
        self.assertEqual(summary['apparel']['closing_pending_orders'], [
            {'order_id':'new-apparel-006','arrival_day':8,'quantity':6},
            {'order_id':'new-apparel-007','arrival_day':9,'quantity':2}])
        for case in summary.values():
            self.assertEqual(sum(o['quantity'] for o in case['closing_pending_orders']),case['closing_on_order'])

    def test_deterministic_run_from_other_working_directory(self):
        outputs=ROOT/'results'
        before={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in outputs.iterdir() if p.is_file()}
        subprocess.run([sys.executable,str(ROOT/'run.py')],cwd=ROOT.parent,check=True,stdout=subprocess.DEVNULL)
        after={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in outputs.iterdir() if p.is_file()}
        self.assertEqual(before,after)


if __name__ == '__main__':
    unittest.main()
